export function searchFoods(query: string): FoodItem[] {
  const q = query.trim().toLowerCase();
  if (!q) return FOOD_CATALOG;
  return FOOD_CATALOG.filter(
    (f) =>
      f.nameFa.includes(query.trim()) ||
      f.nameFa.toLowerCase().includes(q) ||
      f.tags.some((t) => t.includes(q)),
  );
}

export function findFoodById(id: string): FoodItem | undefined {
  return FOOD_CATALOG.find((f) => f.id === id);
}
